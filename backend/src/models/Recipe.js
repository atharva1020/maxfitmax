const mongoose = require('mongoose');

const recipeSchema = new mongoose.Schema({
  creatorId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User',
    required: true,
    index: true
  },
  videoId: {
    type: String, // String UUID or URL or ObjectId matching video upload system
    required: true
  },
  title: {
    type: String,
    required: true,
    trim: true
  },
  baseYieldServings: {
    type: Number,
    required: true,
    default: 1
  },
  ingredients: [{
    ingredientId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'NutritionalDB',
      required: true
    },
    rawQuantityGrams: {
      type: Number,
      required: true
    },
    displayUnit: {
      type: String,
      default: 'g' // e.g. 'cups', 'tbsp', 'g'
    }
  }],
  autoGeneratedDietaryTags: {
    type: [String], // e.g., ['contains_beef', 'contains_dairy', 'contains_pork', 'is_vegan']
    default: [],
    index: true // Indexed for fast filtering in feeds
  },
  cookingMethod: {
    type: String,
    enum: ['raw', 'baked', 'boiled', 'pan_fried', 'deep_fried'],
    required: true,
    default: 'raw'
  },
  calculatedFinalMacros: {
    totalCookedWeightGrams: { type: Number, default: 0 },
    caloriesPerServing: { type: Number, default: 0 },
    proteinPerServing: { type: Number, default: 0 },
    carbsPerServing: { type: Number, default: 0 },
    fatsPerServing: { type: Number, default: 0 }
  },
  structuralTimeline: [{
    stepOrder: { type: Number, required: true },
    instruction: { type: String, required: true },
    durationMinutes: { type: Number, default: 0 }
  }],
  ratings: {
    totalVotes: { type: Number, default: 0 },
    averageScore: { type: Number, default: 0 }
  }
}, {
  timestamps: true
});

// Text index on title for searchability
recipeSchema.index({ title: 'text' });

module.exports = mongoose.model('Recipe', recipeSchema);
