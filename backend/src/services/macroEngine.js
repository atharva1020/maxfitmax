const NutritionalDB = require('../models/NutritionalDB');

/**
 * Calculates cooked mass, adjustments for moisture loss, lipid absorption,
 * and auto-tags recipes based on raw ingredient flags.
 * 
 * @param {Array} ingredients - Array of { ingredientId, rawQuantityGrams }
 * @param {string} cookingMethod - Enum ['raw', 'baked', 'boiled', 'pan_fried', 'deep_fried']
 * @param {number} baseYieldServings - Number of servings the recipe yields
 * @returns {Promise<Object>} Calculated values { totalCookedWeightGrams, caloriesPerServing, proteinPerServing, carbsPerServing, fatsPerServing, autoGeneratedDietaryTags }
 */
async function calculateRecipeMacros(ingredients, cookingMethod, baseYieldServings = 1) {
  if (!ingredients || ingredients.length === 0) {
    throw new Error('No ingredients provided for recipe macro calculation');
  }

  let totalRawMass = 0;
  let totalRawWaterMass = 0;
  
  let totalRawCalories = 0;
  let totalRawProtein = 0;
  let totalRawCarbs = 0;
  let totalRawFats = 0;

  const dietaryFlagsSet = new Set();
  let hasAnimalProducts = false;
  let hasDairy = false;
  let hasBeef = false;
  let hasPork = false;

  // 1. Raw Aggregation
  for (const item of ingredients) {
    const rawIng = await NutritionalDB.findById(item.ingredientId);
    if (!rawIng) {
      throw new Error(`Ingredient not found in NutritionalDB: ${item.ingredientId}`);
    }

    const qty = item.rawQuantityGrams;
    totalRawMass += qty;

    // Water content mass
    const waterPercentage = rawIng.waterContentPercentage || 0;
    totalRawWaterMass += (qty * (waterPercentage / 100));

    // Macro sums (base values are per 100g)
    const factor = qty / 100;
    totalRawCalories += (rawIng.baseMacrosPer100g.calories || 0) * factor;
    totalRawProtein += (rawIng.baseMacrosPer100g.protein || 0) * factor;
    totalRawCarbs += (rawIng.baseMacrosPer100g.carbs || 0) * factor;
    totalRawFats += (rawIng.baseMacrosPer100g.fats || 0) * factor;

    // Gather flags
    if (rawIng.dietaryFlags) {
      rawIng.dietaryFlags.forEach(flag => {
        dietaryFlagsSet.add(flag);
        if (flag === 'is_animal_product') hasAnimalProducts = true;
        if (flag === 'is_dairy') hasDairy = true;
        if (flag === 'is_beef') hasBeef = true;
        if (flag === 'is_pork') hasPork = true;
      });
    }
  }

  let finalCookedMass = totalRawMass;
  let finalCalories = totalRawCalories;
  let finalProtein = totalRawProtein;
  let finalCarbs = totalRawCarbs;
  let finalFats = totalRawFats;

  // 2. Moisture Loss
  // Baked: 0.75 moisture retention factor (MRF) (25% evaporated)
  // Boiled: weight gains slightly or stays same, let's say 1.05 MRF (absorbed water, weight increases)
  if (cookingMethod === 'baked') {
    const mrf = 0.75;
    const evaporatedMass = totalRawWaterMass * (1 - mrf);
    finalCookedMass = Math.max(1, totalRawMass - evaporatedMass);
  } else if (cookingMethod === 'boiled') {
    // Water absorbed, mass increases, but no extra macros
    finalCookedMass = totalRawMass + (totalRawWaterMass * 0.1); 
  }

  // 3. Lipid Absorption (Frying)
  // If pan_fried or deep_fried, calculate oil absorption
  if (cookingMethod === 'deep_fried' || cookingMethod === 'pan_fried') {
    let absorbedOilMass = 0;
    // Frying causes oil absorption based on the solid ingredients' lipidAbsorptionFactor
    for (const item of ingredients) {
      const rawIng = await NutritionalDB.findById(item.ingredientId);
      const absorptionFactor = rawIng.lipidAbsorptionFactor || 0.05; // default 5%
      
      // Calculate how much oil this ingredient absorbs
      const itemAbsorbed = item.rawQuantityGrams * absorptionFactor;
      absorbedOilMass += itemAbsorbed;
    }

    // Add oil absorption to mass and macros
    // 1g of absorbed oil = 9 kcal, 1g fat
    finalCookedMass += absorbedOilMass;
    finalFats += absorbedOilMass;
    finalCalories += absorbedOilMass * 9;
    
    dietaryFlagsSet.add('is_fried');
  }

  // 4. Auto-Tagging Engine
  const autoGeneratedDietaryTags = [];
  if (hasBeef) autoGeneratedDietaryTags.push('contains_beef');
  if (hasPork) autoGeneratedDietaryTags.push('contains_pork');
  if (hasDairy) autoGeneratedDietaryTags.push('contains_dairy');
  
  if (hasAnimalProducts) {
    autoGeneratedDietaryTags.push('contains_animal_products');
  } else {
    // No animal products at all
    autoGeneratedDietaryTags.push('is_vegetarian');
    autoGeneratedDietaryTags.push('is_vegan');
  }

  // If has dairy but no other animal products, it is vegetarian but NOT vegan
  if (hasDairy && !hasBeef && !hasPork && !dietaryFlagsSet.has('is_poultry') && !dietaryFlagsSet.has('is_fish')) {
    if (!autoGeneratedDietaryTags.includes('is_vegetarian')) {
      autoGeneratedDietaryTags.push('is_vegetarian');
    }
    // ensure is_vegan is removed
    const veganIdx = autoGeneratedDietaryTags.indexOf('is_vegan');
    if (veganIdx !== -1) {
      autoGeneratedDietaryTags.splice(veganIdx, 1);
    }
  }

  // Halal tag check: if no pork, no alcohol (can check flag)
  if (!hasPork && !dietaryFlagsSet.has('is_alcohol')) {
    autoGeneratedDietaryTags.push('is_halal');
  }

  // Hindu-No-Beef tag check: if no beef
  if (!hasBeef) {
    autoGeneratedDietaryTags.push('hindu_no_beef_compliant');
  }

  return {
    totalCookedWeightGrams: Math.round(finalCookedMass),
    caloriesPerServing: Math.round(finalCalories / baseYieldServings),
    proteinPerServing: Math.round(finalProtein / baseYieldServings),
    carbsPerServing: Math.round(finalCarbs / baseYieldServings),
    fatsPerServing: Math.round(finalFats / baseYieldServings),
    autoGeneratedDietaryTags
  };
}

module.exports = {
  calculateRecipeMacros
};
