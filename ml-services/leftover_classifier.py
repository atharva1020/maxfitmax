from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.ensemble import RandomForestClassifier
import numpy as np

class LeftoverRouter:
    def __init__(self):
        # We will use TF-IDF to vectorize ingredient names and leftover text strings
        self.vectorizer = TfidfVectorizer(stop_words='english')
        
        # Fit vectorizer with basic food vocabulary
        vocabulary = [
            "chicken breast raw breast fillets chicken meat",
            "white rice grain rice grains",
            "broccoli vegetable florets broccoli head",
            "olive oil oil vegetable oil fat",
            "whole milk dairy fat milk liquid cream",
            "egg egg raw whole egg white yolk",
            "beef steak ribeye raw beef ribeye meat red meat",
            "pork chop raw pork chops pork loin meat"
        ]
        self.vectorizer.fit(vocabulary)
        
        # Create a mock training dataset for Random Forest
        # Features: [overlap_ratio, missing_ingredients_count, is_easy_prep]
        # Target: Match likelihood (0 to 1)
        X_train = np.array([
            [1.0, 0.0, 1.0], # perfect match, no missing ingredients
            [0.6, 2.0, 1.0], # partial match, 2 missing
            [0.3, 4.0, 0.0], # poor match, 4 missing
            [0.8, 1.0, 1.0], # high match, 1 missing
            [0.0, 5.0, 0.0]  # zero match
        ])
        y_train = np.array([1, 1, 0, 1, 0]) # 1 = recommended recipe, 0 = skip
        
        self.classifier = RandomForestClassifier(n_estimators=10, random_state=42)
        self.classifier.fit(X_train, y_train)

    def route_leftovers(self, leftovers_text: str, user_dietary_modes: list, recipes_dataset: list) -> list:
        """
        leftovers_text: "chicken breast, rice, random broccoli"
        user_dietary_modes: ['none']
        recipes_dataset: List of recipe dicts
        """
        # Vectorize user leftovers input
        leftover_vec = self.vectorizer.transform([leftovers_text]).toarray()[0]
        leftover_words = set(leftovers_text.lower().replace(',', ' ').split())

        ranked_recipes = []

        for recipe in recipes_dataset:
            # --- Hard Mask Masking ---
            tags = recipe.get('autoGeneratedDietaryTags', [])
            is_masked = False
            for mode in user_dietary_modes:
                if mode == 'hindu_no_beef' and 'contains_beef' in tags:
                    is_masked = True
                elif mode == 'vegan' and 'is_vegan' not in tags:
                    is_masked = True
                elif mode == 'vegetarian' and 'is_vegetarian' not in tags:
                    is_masked = True
                elif mode == 'halal' and 'is_halal' not in tags:
                    is_masked = True
                elif mode == 'pescetarian' and ('contains_beef' in tags or 'contains_pork' in tags):
                    is_masked = True

            if is_masked:
                continue

            # --- Overlap & Feature Extraction ---
            recipe_ingredients = [ing.get('name', '').lower() for ing in recipe.get('ingredients', [])]
            recipe_text = " ".join(recipe_ingredients)
            recipe_vec = self.vectorizer.transform([recipe_text]).toarray()[0]
            
            # Feature 1: Overlap ratio (Cosine similarity of TF-IDF vectors)
            dot_product = np.dot(leftover_vec, recipe_vec)
            norm_leftover = np.linalg.norm(leftover_vec)
            norm_recipe = np.linalg.norm(recipe_vec)
            similarity = dot_product / (norm_leftover * norm_recipe + 1e-9)

            # Feature 2: Missing ingredients (how many recipe ingredients are NOT in user leftovers)
            missing_count = 0
            for ring in recipe_ingredients:
                words_in_ring = set(ring.split())
                if not words_in_ring.intersection(leftover_words):
                    missing_count += 1

            # Feature 3: Ease of preparation (based on timeline steps)
            timeline = recipe.get('structuralTimeline', [])
            is_easy_prep = 1.0 if len(timeline) <= 4 else 0.0

            # Predict recommendation class probability using RF
            features = np.array([[similarity, float(missing_count), is_easy_prep]])
            prob = self.classifier.predict_proba(features)[0][1] # Probability of class 1 (recommend)

            ranked_recipes.append({
                "recipeId": recipe.get('_id'),
                "title": recipe.get('title'),
                "videoId": recipe.get('videoId'),
                "similarity_score": float(similarity),
                "missing_ingredients_count": missing_count,
                "matching_probability": float(prob)
            })

        # Rank by probability first, then by similarity score (descending)
        ranked_recipes.sort(key=lambda x: (x['matching_probability'], x['similarity_score']), reverse=True)
        return ranked_recipes

router = LeftoverRouter()

def match_leftovers(leftovers_text: str, user_dietary_modes: list, recipes_dataset: list) -> list:
    return router.route_leftovers(leftovers_text, user_dietary_modes, recipes_dataset)
